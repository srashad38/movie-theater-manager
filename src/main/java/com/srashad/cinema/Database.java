package com.srashad.cinema;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.*;

/** Opens short-lived connections; each operation owns and closes its resources. */
public final class Database {
    private final String url;
    public Database(String url) {
        if (!url.startsWith("jdbc:h2:")) throw new IllegalArgumentException("An H2 database URL is required.");
        this.url = url;
    }
    public static Database local(Path directory) throws Exception {
        Files.createDirectories(directory);
        return new Database("jdbc:h2:file:" + directory.toAbsolutePath().resolve("cinema") + ";DB_CLOSE_ON_EXIT=FALSE");
    }
    public Connection open() throws SQLException { return DriverManager.getConnection(url, "sa", ""); }
    public void initialize() throws SQLException {
        try (Connection c = open(); Statement s = c.createStatement()) {
            s.execute("""
                CREATE TABLE IF NOT EXISTS movies (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  title VARCHAR(160) NOT NULL, genre VARCHAR(60) NOT NULL,
                  minutes INT NOT NULL CHECK (minutes BETWEEN 1 AND 600), rating VARCHAR(12) NOT NULL)
                """);
            s.execute("""
                CREATE TABLE IF NOT EXISTS auditoriums (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  name VARCHAR(60) NOT NULL UNIQUE, capacity INT NOT NULL CHECK (capacity > 0))
                """);
            s.execute("""
                CREATE TABLE IF NOT EXISTS screenings (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  movie_id BIGINT NOT NULL REFERENCES movies(id),
                  auditorium_id BIGINT NOT NULL REFERENCES auditoriums(id),
                  starts_at TIMESTAMP NOT NULL,
                  price DECIMAL(10,2) NOT NULL CHECK (price >= 0),
                  UNIQUE(auditorium_id, starts_at))
                """);
            s.execute("""
                CREATE TABLE IF NOT EXISTS bookings (
                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  screening_id BIGINT NOT NULL REFERENCES screenings(id),
                  customer VARCHAR(100) NOT NULL,
                  quantity INT NOT NULL CHECK (quantity BETWEEN 1 AND 20),
                  total DECIMAL(12,2) NOT NULL CHECK (total >= 0),
                  status ENUM('ACTIVE', 'CANCELLED') NOT NULL,
                  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)
                """);
            s.execute("CREATE INDEX IF NOT EXISTS booking_screening_status ON bookings(screening_id, status)");
            s.execute("CREATE INDEX IF NOT EXISTS screening_room_time ON screenings(auditorium_id, starts_at)");
            // Idempotent reference data, never resets user movies or bookings.
            s.execute("INSERT INTO auditoriums(name,capacity) SELECT 'Screen 1',80 WHERE NOT EXISTS (SELECT 1 FROM auditoriums WHERE name='Screen 1')");
            s.execute("INSERT INTO auditoriums(name,capacity) SELECT 'Screen 2',48 WHERE NOT EXISTS (SELECT 1 FROM auditoriums WHERE name='Screen 2')");
            s.execute("INSERT INTO auditoriums(name,capacity) SELECT 'Studio',24 WHERE NOT EXISTS (SELECT 1 FROM auditoriums WHERE name='Studio')");
        }
    }
}
